import { useEffect, useState } from "react";
import { FaFileWaveform, FaDownload, FaCalendarDays } from "react-icons/fa6";
import { fetchReports, generateReport, downloadReport } from "../services/hospitalAdminApi.js";

const reportTypes = ["All", "Performance", "Readmission", "Outcomes", "Operations", "Risk"];

export function HospitalAdminReportsPage() {
  const [reportCatalog, setReportCatalog] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [generating, setGenerating] = useState(false);
  const [activeType, setActiveType] = useState("All");

  useEffect(() => {
    async function loadReports() {
      try {
        setLoading(true);
        const data = await fetchReports();
        setReportCatalog(data);
      } catch (err) {
        setError(err.message);
      } finally {
        setLoading(false);
      }
    }
    loadReports();
  }, []);

  const filteredReports =
    activeType === "All"
      ? reportCatalog
      : reportCatalog.filter((report) => report.type === activeType);

  const handleGenerateReport = async () => {
    try {
      setGenerating(true);
      const newReport = await generateReport("Performance");
      setReportCatalog((prev) => [newReport, ...prev]);
    } catch (err) {
      setError(err.message);
    } finally {
      setGenerating(false);
    }
  };

  const handleDownload = async (report) => {
    try {
      await downloadReport(report.id, `${report.title.replace(/\s+/g, "-").toLowerCase()}.txt`);
    } catch (err) {
      setError(err.message);
    }
  };

  if (loading) {
    return (
      <section className="dashboard-page-header">
        <h1>Loading reports...</h1>
      </section>
    );
  }

  return (
    <>
      <section className="dashboard-page-header">
        <h1>Reports</h1>
        <p>
          Generate, review, and download hospital-wide performance and
          readmission reports.
        </p>
      </section>

      {error && (
        <div className="settings-error-banner" style={{ marginBottom: "16px" }}>
          {error}
        </div>
      )}

      <section className="dashboard-content-grid">
        <article className="dashboard-panel dashboard-table-panel" style={{ gridColumn: "1 / -1" }}>
          <div className="panel-header-row">
            <div>
              <h2>Report Library</h2>
              <p>Filter by report type and download completed reports</p>
            </div>

            <div className="dashboard-inline-actions">
              <button
                type="button"
                className="primary-button"
                onClick={handleGenerateReport}
                disabled={generating}
              >
                <FaFileWaveform /> {generating ? "Generating..." : "Generate New Report"}
              </button>
            </div>
          </div>

          <div className="dashboard-inline-actions" style={{ marginBottom: "1rem", flexWrap: "wrap" }}>
            {reportTypes.map((type) => (
              <button
                key={type}
                type="button"
                className={type === activeType ? "primary-button" : "secondary-button"}
                onClick={() => setActiveType(type)}
              >
                {type}
              </button>
            ))}
          </div>

          <div className="dashboard-table-wrap">
            <table className="dashboard-table">
              <thead>
                <tr>
                  <th>Report</th>
                  <th>Type</th>
                  <th>
                    <FaCalendarDays /> Period
                  </th>
                  <th>Generated By</th>
                  <th>Status</th>
                  <th>Action</th>
                </tr>
              </thead>

              <tbody>
                {filteredReports.length === 0 ? (
                  <tr>
                    <td colSpan={6}>No reports generated yet. Click "Generate New Report" to create one.</td>
                  </tr>
                ) : (
                  filteredReports.map((report) => (
                    <tr key={report.id}>
                      <td>{report.title}</td>
                      <td>{report.type}</td>
                      <td>{report.period}</td>
                      <td>{report.generatedBy}</td>
                      <td>
                        <span
                          className={`risk-pill ${report.status === "Ready" ? "low" : "high"}`}
                        >
                          {report.status}
                        </span>
                      </td>
                      <td>
                        <button
                          type="button"
                          className="secondary-button"
                          disabled={report.status !== "Ready"}
                          onClick={() => handleDownload(report)}
                        >
                          <FaDownload /> Download
                        </button>
                      </td>
                    </tr>
                  ))
                )}
              </tbody>
            </table>
          </div>
        </article>
      </section>
    </>
  );
}