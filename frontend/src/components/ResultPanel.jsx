import {
  FaCircleCheck,
  FaCircleExclamation,
  FaHeartPulse,
  FaShieldHeart,
} from 'react-icons/fa6'

export function ResultPanel({ result, onReset }) {
  const riskProfile = getRiskProfile(result)
  const confidenceValue = Number.parseFloat(result.confidence) || 0
  const confidencePercent = Math.min(100, Math.max(0, confidenceValue))
  const confidenceDisplay = `${confidencePercent.toFixed(1)}%`

  const radius = 50
  const circumference = 2 * Math.PI * radius
  const dashOffset = circumference * (1 - confidencePercent / 100)

  return (
    <div className="result-panel">
      <div className="result-header">
        <h2>Prediction Complete</h2>
        {result.patientName && (
          <p className="result-patient-name">Patient: {result.patientName}</p>
        )}
        <p className="result-timestamp">Generated: {result.timestamp}</p>
      </div>

      <div className="result-score-container">
        <div className="result-score-card" style={{ borderLeftColor: riskProfile.color }}>
          <div className="result-score-top">
            <div className="score-ring-wrap">
              <svg className="score-ring-svg" viewBox="0 0 120 120">
                <circle
                  className="score-ring-track"
                  cx="60"
                  cy="60"
                  r={radius}
                  strokeWidth="10"
                  fill="none"
                />
                <circle
                  className="score-ring-progress"
                  cx="60"
                  cy="60"
                  r={radius}
                  strokeWidth="10"
                  fill="none"
                  stroke={riskProfile.color}
                  strokeDasharray={circumference}
                  strokeDashoffset={dashOffset}
                  strokeLinecap="round"
                  transform="rotate(-90 60 60)"
                />
              </svg>
              <div className="score-ring-center">
                <strong style={{ color: riskProfile.color }}>{confidenceDisplay}</strong>
                <span>Confidence</span>
              </div>
            </div>

            <div className="score-content">
              <div className="result-badges">
                <span className="result-badge" style={{ background: riskProfile.tint, color: riskProfile.color }}>
                  {riskProfile.label}
                </span>
                <span className="result-badge muted">Model output</span>
              </div>
              <p className="score-label">Prediction</p>
              <p className="score-value" style={{ color: riskProfile.color }}>
                {result.result}
              </p>
            </div>
          </div>

          <div className="result-metric-grid">
            <div className="result-metric">
              <span>Raw Prediction</span>
              <strong>{result.prediction}</strong>
            </div>
            <div className="result-metric">
              <span>Risk level</span>
              <strong>{result.riskLevel}</strong>
            </div>
          </div>

          <p className="result-message-inline">{result.message}</p>
        </div>
      </div>

      <div className="result-details-grid">
        <div className="result-detail-card">
          <FaHeartPulse aria-hidden="true" />
          <div>
            <span>Prediction</span>
            <strong>{result.prediction}</strong>
          </div>
        </div>
        <div className="result-detail-card">
          <FaShieldHeart aria-hidden="true" />
          <div>
            <span>Status</span>
            <strong>{result.result}</strong>
          </div>
        </div>
        <div className="result-detail-card">
          {result.riskLevel === 'Low' ? <FaCircleCheck aria-hidden="true" /> : <FaCircleExclamation aria-hidden="true" />}
          <div>
            <span>Risk level</span>
            <strong>{result.riskLevel}</strong>
          </div>
        </div>
      </div>

      <div className="result-actions">
        <button type="button" className="btn-new-prediction" onClick={onReset}>
          Generate Another Prediction
        </button>
        <a href="#home" className="btn-return-home">
          Return to Home
        </a>
      </div>

      <div className="result-disclaimer">
        <h3>Important Disclaimer</h3>
        <p>
          This prediction is generated by a machine learning model and should
          be used as a decision support tool only. It does not replace clinical
          judgment or professional medical advice. Always consult with the care
          team before making patient care decisions.
        </p>
      </div>
    </div>
  )
}

function getRiskProfile(result) {
  if (result.riskLevel === 'Low') {
    return {
      label: 'Low risk',
      color: '#059669',
      tint: 'rgba(16, 185, 129, 0.12)',
      icon: <FaCircleCheck />,
    }
  }

  return {
    label: 'High risk',
    color: '#dc2626',
    tint: 'rgba(220, 38, 38, 0.12)',
    icon: <FaCircleExclamation />,
  }
}