import { useState } from "react";
import { useOutletContext } from "react-router-dom";
import { FaFileWaveform, FaDownload, FaCalendarDays } from "react-icons/fa6";

const initialReports = [
  {
    id: "RPT-2026-07-W3",
    title: "Weekly Hospital Performance Report",
    type: "Performance",
    period: "20 Jul – 26 Jul 2026",
    generatedBy: "System",
    status: "Ready",
  },
  {
    id: "RPT-2026-07-READ",
    title: "Readmission Trend Report",
    type: "Readmission",
    period: "01 Jul – 26 Jul 2026",
    generatedBy: "System",
    status: "Ready",
  },
  {
    id: "RPT-2026-06-OUT",
    title: "Patient Outcome Summary",
    type: "Outcomes",
    period: "June 2026",
    generatedBy: "Michael Torres",
    status: "Ready",
  },
  {
    id: "RPT-2026-06-DEPT",
    title: "Department-wise Bed Occupancy Report",
    type: "Operations",
    period: "June 2026",
    generatedBy: "System",
    status: "Ready",
  },
  {
    id: "RPT-2026-07-QUEUE",
    title: "Endocrinology Risk Escalation Report",
    type: "Risk",
    period: "In progress",
    generatedBy: "System",
    status: "Generating",
  },
];

const reportTypes = ["All", "Performance", "Readmission", "Outcomes", "Operations", "Risk"];

export function HospitalAdminReportsPage() {
  const { user } = useOutletContext();
  const [activeType, setActiveType] = useState("All");
  const [reportCatalog, setReportCatalog] = useState(initialReports);

  const filteredReports =
    activeType === "All"
      ? reportCatalog
      : reportCatalog.filter((report) => report.type === activeType);

  const handleGenerateReport = () => {
    const newId = `RPT-${Date.now()}`;
    const today = new Date().toLocaleDateString("en-GB", {
      day: "2-digit",
      month: "short",
      year: "numeric",
    });

    const newReport = {
      id: newId,
      title: "Hospital Performance Report",
      type: "Performance",
      period: today,
      generatedBy: user?.fullName || "You",
      status: "Generating",
    };

    setReportCatalog((prev) => [newReport, ...prev]);

    // simulate report generation finishing
    setTimeout(() => {
      setReportCatalog((prev) =>
        prev.map((r) => (r.id === newId ? { ...r, status: "Ready" } : r))
      );
    }, 2000);
  };

  const handleDownload = (report) => {
    const content = `Report: ${report.title}
Type: ${report.type}
Period: ${report.period}
Generated By: ${report.generatedBy}
Status: ${report.status}
`;

    const blob = new Blob([content], { type: "text/plain;charset=utf-8;" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.setAttribute("download", `${report.id}.txt`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <>
      <section className="dashboard-page-header">
        <h1>Reports</h1>
        <p>
          Generate, review, and download hospital-wide performance and
          readmission reports.
        </p>
      </section>

      <section className="dashboard-content-grid">
        <article className="dashboard-panel dashboard-table-panel" style={{ gridColumn: "1 / -1" }}>
          <div className="panel-header-row">
            <div>
              <h2>Report Library</h2>
              <p>Filter by report type and download completed reports</p>
            </div>

            <div className="dashboard-inline-actions">
              <button type="button" className="primary-button" onClick={handleGenerateReport}>
                <FaFileWaveform /> Generate New Report
              </button>
            </div>
          </div>

          <div className="dashboard-inline-actions" style={{ marginBottom: "1rem", flexWrap: "wrap" }}>
            {reportTypes.map((type) => (
              <button
                key={type}
                type="button"
                className={type === activeType ? "primary-button" : "secondary-button"}
                onClick={() => setActiveType(type)}
              >
                {type}
              </button>
            ))}
          </div>

          <div className="dashboard-table-wrap">
            <table className="dashboard-table">
              <thead>
                <tr>
                  <th>Report</th>
                  <th>Type</th>
                  <th>
                    <FaCalendarDays /> Period
                  </th>
                  <th>Generated By</th>
                  <th>Status</th>
                  <th>Action</th>
                </tr>
              </thead>

              <tbody>
                {filteredReports.map((report) => (
                  <tr key={report.id}>
                    <td>{report.title}</td>
                    <td>{report.type}</td>
                    <td>{report.period}</td>
                    <td>{report.generatedBy}</td>
                    <td>
                      <span
                        className={`risk-pill ${report.status === "Ready" ? "low" : "high"}`}
                      >
                        {report.status}
                      </span>
                    </td>
                    <td>
                      <button
                        type="button"
                        className="secondary-button"
                        disabled={report.status !== "Ready"}
                        onClick={() => handleDownload(report)}
                      >
                        <FaDownload /> Download
                      </button>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </article>
      </section>
    </>
  );
}