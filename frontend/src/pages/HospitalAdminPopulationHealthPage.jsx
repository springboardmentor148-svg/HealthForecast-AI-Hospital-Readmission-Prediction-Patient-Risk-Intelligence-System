import { useEffect, useState } from "react";
import { FaUsers, FaHeartPulse, FaChartPie, FaDownload } from "react-icons/fa6";
import { fetchPopulationHealth } from "../services/hospitalAdminApi.js";

const statIcons = {
  "Total Patients Tracked": FaUsers,
  "Chronic Condition Patients": FaHeartPulse,
  "Avg. Age": FaChartPie,
};

// Reports list — abhi static hai, Reports page banne ke baad isse bhi backend se connect karenge
const reports = [
  { title: "Q3 2026 Population Health Summary", period: "Jul - Sep 2026", status: "Ready" },
  { title: "Chronic Disease Prevalence Report", period: "Jan - Jun 2026", status: "Ready" },
  { title: "Age Group Risk Distribution", period: "2026 YTD", status: "Ready" },
];

export function HospitalAdminPopulationHealthPage() {
  const [populationData, setPopulationData] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  useEffect(() => {
    async function loadPopulationHealth() {
      try {
        setLoading(true);
        const data = await fetchPopulationHealth();
        setPopulationData(data);
      } catch (err) {
        setError(err.message);
      } finally {
        setLoading(false);
      }
    }
    loadPopulationHealth();
  }, []);

  const handleDownloadReport = (report) => {
    const content = `Report: ${report.title}
Period: ${report.period}
Status: ${report.status}

This is a population health report generated by HealthForecastAI.
`;

    const blob = new Blob([content], { type: "text/plain;charset=utf-8;" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `${report.title.replace(/\s+/g, "-").toLowerCase()}.txt`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  if (loading) {
    return (
      <section className="dashboard-page-header">
        <h1>Loading population health data...</h1>
      </section>
    );
  }

  if (error) {
    return (
      <section className="dashboard-page-header">
        <h1>Population Health Reports</h1>
        <p style={{ color: "red" }}>{error}</p>
      </section>
    );
  }

  return (
    <>
      <section className="dashboard-page-header">
        <h1>Population Health Reports</h1>
        <p>Hospital-wide health trends and chronic condition patterns across your patient population.</p>
      </section>

      <section className="dashboard-card-grid">
        {populationData.stats.map((card) => {
          const Icon = statIcons[card.label] || FaChartPie;
          return (
            <article key={card.label} className="dashboard-metric-card">
              <div className="metric-icon">
                <Icon />
              </div>
              <span>{card.label}</span>
              <strong>{card.value}</strong>
            </article>
          );
        })}
      </section>

      <section className="dashboard-content-grid">
        <article className="dashboard-panel dashboard-table-panel">
          <div className="panel-header-row">
            <div>
              <h2>Condition Breakdown</h2>
              <p>Patient count and readmission rate by chronic condition</p>
            </div>
          </div>

          <div className="dashboard-table-wrap">
            <table className="dashboard-table">
              <thead>
                <tr>
                  <th>Condition</th>
                  <th>Patients</th>
                  <th>Avg. Readmission Rate</th>
                </tr>
              </thead>
              <tbody>
                {populationData.conditionBreakdown.length === 0 ? (
                  <tr>
                    <td colSpan={3}>No patient conditions recorded yet.</td>
                  </tr>
                ) : (
                  populationData.conditionBreakdown.map((row) => (
                    <tr key={row.condition}>
                      <td>{row.condition}</td>
                      <td>{row.patients}</td>
                      <td>{row.avgReadmission}</td>
                    </tr>
                  ))
                )}
              </tbody>
            </table>
          </div>
        </article>

        <aside className="dashboard-side-stack">
          <article className="dashboard-panel">
            <h2>Available Reports</h2>

            <ul className="notification-list">
              {reports.map((report, index) => (
                <li key={index} className="notification-item">
                  <span className="notification-icon tone-info">
                    <FaChartPie />
                  </span>
                  <div className="notification-body" style={{ flex: 1 }}>
                    <p>{report.title}</p>
                    <span className="notification-time">{report.period}</span>
                  </div>
                  <button
                    type="button"
                    className="icon-button"
                    aria-label={`Download ${report.title}`}
                    onClick={() => handleDownloadReport(report)}
                  >
                    <FaDownload />
                  </button>
                </li>
              ))}
            </ul>
          </article>
        </aside>
      </section>
    </>
  );
}